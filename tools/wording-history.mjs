// Fingerprints of every version of Connect's assignment wording ever shipped (git history of assignment-defaults.js,
// and the superseded versions it lists), so a course holding an older copy is still known as Connect's assignment.
// Writes assignment-history.js. Run after changing the wording:  node tools/wording-history.mjs
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import vm from 'node:vm';
const fp = a => { const t = JSON.stringify({ s: a.sections || [], c: (a.criteria || []).map(c => typeof c === 'string' ? c : c && c.text) }); let h = 5381; for (let i = 0; i < t.length; i++) h = ((h * 33) ^ t.charCodeAt(i)) >>> 0; return h.toString(36) + '.' + t.length.toString(36); };
const shas = execFileSync('git', ['log', '--format=%H', '--', 'assignment-defaults.js']).toString().trim().split('\n');
const out = {};
const add = (k, a) => { if (!a || !a.sections) return; (out[k] = out[k] || new Set()).add(fp(a)); };
for (const sha of shas) {
  let src; try { src = execFileSync('git', ['show', sha + ':assignment-defaults.js'], { maxBuffer: 64 << 20 }).toString(); } catch (e) { continue; }
  const box = { window: {} }; try { vm.runInNewContext(src, box); } catch (e) { continue; }
  const w = box.window;
  Object.entries(w.CONNECT_HUB_DEFAULT_WORDING || {}).forEach(([k, a]) => add(k, a));
  const sup = w.CONNECT_HUB_SUPERSEDED_WORDING; (Array.isArray(sup) ? sup : sup ? [sup] : []).forEach(v => Object.entries(v || {}).forEach(([k, a]) => add(k, a)));
}
const obj = Object.fromEntries(Object.entries(out).map(([k, s]) => [k, [...s].sort()]));
writeFileSync('assignment-history.js', '// Generated by tools/wording-history.mjs: a fingerprint of every version of Connect’s assignment wording.\n// hubIsConnectsAsg (hub-shared.js) reads it. Do not edit by hand.\nwindow.CONNECT_HUB_WORDING_FP = ' + JSON.stringify(obj) + ';\n');
console.log(Object.entries(obj).map(([k, v]) => k + ' ' + v.length).join(', '), 'from', shas.length, 'versions');
